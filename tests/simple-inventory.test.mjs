import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { test } from "node:test";
import { PGlite } from "@electric-sql/pglite";
const admin = "11111111-1111-4111-8111-111111111111";
const cashier = "22222222-2222-4222-8222-222222222222";
test("inventario simple: activa sin cambiar precios, porcentaje global seguro y permisos", async (t) => {
  const db = await PGlite.create(); t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key,email text);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth to authenticated;
    insert into auth.users values('${admin}','a@x'),('${cashier}','c@x');`);
  const dir = new URL("../supabase/migrations/",import.meta.url);
  for (const name of (await readdir(dir)).filter(name=>!name.includes("010")).sort()) await db.exec(await readFile(new URL(name,dir),"utf8"));
  await db.exec(`insert into public.profiles(id,username,role,register_no) values('${admin}','admin','admin',null),('${cashier}','caja1','cashier',1);`);
  const as = async (id) => { await db.exec("reset role"); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); await db.exec("set role authenticated"); };
  const rpc = async (expr,args=[]) => (await db.query("select "+expr+" as r",args)).rows[0].r;
  await as(admin);
  const legacy=await rpc("public.save_product($1)",[{code:"LEGACY",name:"Precio anterior",price:7.35,active:false,barcode:"ABC",category:"Categoría conservada"}]);
  const unpriced=await rpc("public.save_product($1)",[{code:"SIN-PRECIO",name:"Sin costo"}]);
  await db.exec("reset role");
  await db.exec(await readFile(new URL("202611140010_inventario_simple.sql",dir),"utf8"));
  await as(admin);
  let catalog=await rpc("public.catalog()");
  assert.equal(catalog.simple_pricing_enabled,true); assert.equal(catalog.settings.markup_percent,25);
  assert.ok(catalog.products.every(p=>p.active));
  let old=catalog.products.find(p=>p.id===legacy);
  assert.equal(old.price,7.35); assert.equal(catalog.products.find(p=>p.id===unpriced).price,null);
  const id=await rpc("public.save_simple_product($1)",[{name:"Nuevo",net_cost:"10",expected_markup:25,markup_percent:999,price:999,stock:999}]);
  let product=(await rpc("public.catalog()")).products.find(p=>p.id===id);
  assert.equal(product.price,12.5); assert.equal(product.stock,0);assert.equal(product.net_cost,10);assert.equal(product.markup_percent,25);assert.match(product.code,/^FW-/);
  await rpc("public.save_simple_product($1,$2)",[{id:legacy,name:"Solo nombre",expected_markup:25},old.updated_at]);
  old=(await rpc("public.catalog()")).products.find(p=>p.id===legacy);
  assert.equal(old.price,7.35);assert.equal(old.barcode,"ABC");assert.equal(old.category,"Categoría conservada");
  await assert.rejects(rpc("public.save_simple_product($1,$2)",[{id,name:"Obsoleto",net_cost:1,expected_markup:25},"2000-01-01"]),/cambió/);
  await assert.rejects(rpc("public.save_markup_percent($1,$2)",[-1,25]),/porcentaje/);
  await assert.rejects(rpc("public.save_markup_percent($1,$2)",[30,0]),/cambió/);
  const beforePriceId=product.price_id;
  await rpc("public.save_markup_percent($1,$2)",[30,25]);
  catalog=await rpc("public.catalog()");product=catalog.products.find(p=>p.id===id);
  assert.equal(product.price,13);assert.equal(product.markup_percent,30);assert.notEqual(product.price_id,beforePriceId);
  assert.equal(catalog.products.find(p=>p.id===legacy).price,7.35);
  assert.equal(catalog.products.find(p=>p.id===unpriced).price,null);
  await assert.rejects(rpc("public.save_simple_product($1,$2)",[{id,name:"Costo viejo",net_cost:20,expected_markup:25},product.updated_at]),/porcentaje general cambió/);
  await rpc("public.save_simple_product($1,$2)",[{id,name:"Nuevo costo",net_cost:20,expected_markup:30,barcode:"NO"},product.updated_at]);
  product=(await rpc("public.catalog()")).products.find(p=>p.id===id);assert.equal(product.price,26);assert.equal(product.barcode,null);
  await as(cashier);
  await assert.rejects(rpc("public.save_markup_percent($1,$2)",[40,30]),/no autorizada/);
  await assert.rejects(rpc("public.save_simple_product($1)",[{name:"No",net_cost:1,expected_markup:30}]),/no autorizada/);
  catalog=await rpc("public.catalog()"); assert.equal(catalog.products.find(p=>p.id===id).price,26);
  assert.equal(Object.hasOwn(catalog.products.find(p=>p.id===id),"net_cost"),false);
  assert.equal(catalog.products.some(p=>p.id===unpriced),false);
});
